using System.Diagnostics;
using System.Globalization;
using System.Reflection;
using System.Runtime;
using System.Runtime.InteropServices;
using Microsoft.Win32;

namespace AStar.Experiments;

/// <summary>
/// Writes <c>environment.md</c>: the technical report of the measurement
/// environment — language, runtime, OS, CPU, RAM, timing method and the build
/// settings that affect the timings.
/// <para>
/// Every value is probed at run time rather than typed in, so the report cannot
/// drift from the machine the measurements were actually taken on.
/// </para>
/// </summary>
public static class EnvironmentProbe
{
    /// <summary>The report's file name, beside <c>runs.csv</c> in the results directory.</summary>
    public const string FileName = "environment.md";

    /// <summary>
    /// The compiler's language version — the one value here that is not probed,
    /// because the runtime keeps no record of it. C# 14 is the default for
    /// <c>net10.0</c> and the csproj sets no <c>LangVersion</c>, so it follows
    /// from the target framework.
    /// </summary>
    private const string LanguageVersion = "C# 14";

    /// <summary>Set by the compiler, so a Debug build reports itself as one.</summary>
#if DEBUG
    private const string BuildConfiguration = "Debug";
#else
    private const string BuildConfiguration = "Release";
#endif

    private const string ProcessorKey = @"HARDWARE\DESCRIPTION\System\CentralProcessor\0";
    private const string WindowsVersionKey = @"SOFTWARE\Microsoft\Windows NT\CurrentVersion";

    /// <summary>The first Windows 11 build. See <see cref="OperatingSystemName"/>.</summary>
    private const int FirstWindows11Build = 22000;

    /// <summary>
    /// Probes the machine and writes the report, returning the path it wrote.
    /// <paramref name="masterSeed"/> is recorded because it is what makes the
    /// numbers in <c>runs.csv</c> reproducible on this machine.
    /// </summary>
    public static string Write(string resultsDirectory, long masterSeed)
    {
        Directory.CreateDirectory(resultsDirectory);
        string path = Path.Combine(resultsDirectory, FileName);
        File.WriteAllText(path, Report(masterSeed));
        return path;
    }

    /// <summary>
    /// The report itself, as Markdown. Split out from <see cref="Write"/> so it
    /// can be inspected without writing a file.
    /// </summary>
    public static string Report(long masterSeed)
    {
        var text = new System.Text.StringBuilder();

        text.AppendLine("# Measurement environment");
        text.AppendLine();
        text.AppendLine("Machine-generated by `EnvironmentProbe`. Every value below is read from the");
        text.AppendLine("running process rather than typed in, so it describes the machine that");
        text.AppendLine("produced the `runs.csv` in this directory. Rewritten on every harness run.");
        text.AppendLine();
        text.AppendLine($"Probed {DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture)} " +
                        $"local time ({TimeZoneInfo.Local.StandardName}).");
        text.AppendLine();

        text.AppendLine("## Program");
        text.AppendLine();
        AppendRow(text, "Language", LanguageVersion);
        AppendRow(text, "Target framework", AppContext.TargetFrameworkName ?? "unknown");
        AppendRow(text, "Runtime", RuntimeInformation.FrameworkDescription);
        AppendRow(text, "Build configuration", BuildConfiguration);
        AppendRow(text, "Process architecture", RuntimeInformation.ProcessArchitecture.ToString());
        AppendRow(text, "Third-party libraries", "none");
        AppendRow(text, "Assemblies referenced", ReferencedAssemblies());
        text.AppendLine();
        text.AppendLine("Every assembly listed above ships with .NET itself; the project file declares");
        text.AppendLine("no `PackageReference`. The PNG figures are written by a hand-rolled encoder");
        text.AppendLine("over `System.IO.Compression.ZLibStream` for exactly this reason.");
        text.AppendLine();

        // Preprocessor rather than a test on BuildConfiguration: that is a
        // compile-time constant, so either branch would be unreachable code.
#if DEBUG
        text.AppendLine("> **This is not a Release build.** Debug timings run roughly twice as slow");
        text.AppendLine("> and must not be used as measurements.");
        text.AppendLine();
#endif

        text.AppendLine("## Machine");
        text.AppendLine();
        AppendRow(text, "CPU", CpuName());
        AppendRow(text, "Cores / threads", CoreCount());
        AppendRow(text, "Nominal clock", NominalClock());
        AppendRow(text, "RAM", TotalMemory());
        AppendRow(text, "Operating system", OperatingSystemName());
        AppendRow(text, "OS architecture", RuntimeInformation.OSArchitecture.ToString());
        text.AppendLine();
        text.AppendLine("Every search in the study is single-threaded, so the core count bears on");
        text.AppendLine("nothing except how little the rest of the machine interferes.");
        text.AppendLine();

        text.AppendLine("## How execution time is measured");
        text.AppendLine();
        AppendRow(text, "Clock", "`System.Diagnostics.Stopwatch`");
        AppendRow(text, "High resolution", Stopwatch.IsHighResolution ? "yes" : "NO — timings are unreliable");
        AppendRow(text, "Tick frequency", $"{Stopwatch.Frequency.ToString("N0", CultureInfo.InvariantCulture)} Hz");
        AppendRow(text, "Tick resolution", TickResolution());
        AppendRow(text, "Measured region", "the `Search` call and nothing else");
        AppendRow(text, "Memory metric", "`GC.GetTotalAllocatedBytes(precise: true)` delta across the search");
        text.AppendLine();
        text.AppendLine("Map generation, endpoint sampling, figure rendering and CSV writing all sit");
        text.AppendLine("outside the clock. A full blocking garbage collection is forced before each");
        text.AppendLine("timed search, also outside the clock. `methodology.md` gives the reasoning.");
        text.AppendLine();

        text.AppendLine("## Runtime settings that affect the timings");
        text.AppendLine();
        AppendRow(text, "Tiered compilation", Switch("System.Runtime.TieredCompilation"));
        AppendRow(text, "Tiered PGO", Switch("System.Runtime.TieredPGO"));
        AppendRow(text, "Server GC", GCSettings.IsServerGC ? "enabled" : "disabled (workstation)");
        AppendRow(text, "GC latency mode", GCSettings.LatencyMode.ToString());
        AppendRow(text, "Warmup per variant", $"{ExperimentRunner.WarmupExecutions} executions, discarded");
        text.AppendLine();
        text.AppendLine("Tiered compilation is disabled in the project file, not just for Release.");
        text.AppendLine("Leaving it enabled inflates the cheapest searches most and compresses the");
        text.AppendLine("measured A*-over-Dijkstra advantage by about a factor of four — a bias that is");
        text.AppendLine("invisible in the data, because the wrong timings are flat and reproducible.");
        text.AppendLine();

        text.AppendLine("## Reproducing the numbers");
        text.AppendLine();
        AppendRow(text, "Master seed", masterSeed.ToString(CultureInfo.InvariantCulture));
        AppendRow(text, "Runs per configuration",
            $"{ExperimentMatrix.RunsPerConfiguration} maps x 3 algorithms = " +
            $"{ExperimentMatrix.RunsPerConfiguration * 3} executions");
        text.AppendLine();
        text.AppendLine("The master seed above is the one this invocation used. `runs.csv` accumulates");
        text.AppendLine("across invocations, so every row also carries its own `master_seed`, `map_seed`");
        text.AppendLine("and `pair_seed` — one row is enough to rebuild the exact environment it");
        text.AppendLine("describes. See `methodology.md` for the seed scheme and the generators.");

        return text.ToString();
    }

    // ------------------------------------------------------------- formatting

    private static void AppendRow(System.Text.StringBuilder text, string name, string value) =>
        text.AppendLine($"- **{name}:** {value}");

    private static string TickResolution()
    {
        double nanoseconds = 1e9 / Stopwatch.Frequency;
        return $"{nanoseconds.ToString("F1", CultureInfo.InvariantCulture)} ns per tick";
    }

    /// <summary>
    /// An <see cref="AppContext"/> switch as the runtime sees it. Read from the
    /// switch rather than from the csproj, so what is reported is what the
    /// process actually ran with.
    /// </summary>
    private static string Switch(string name) =>
        AppContext.TryGetSwitch(name, out bool enabled)
            ? (enabled ? "enabled" : "disabled")
            : "not set (runtime default)";

    /// <summary>
    /// The assemblies this program actually binds to — the evidence behind the
    /// "no third-party libraries" claim, rather than a restatement of it.
    /// </summary>
    private static string ReferencedAssemblies()
    {
        var names = Assembly.GetExecutingAssembly()
            .GetReferencedAssemblies()
            .Select(assembly => assembly.Name ?? "")
            .Where(name => name.Length > 0)
            .OrderBy(name => name, StringComparer.Ordinal);

        return string.Join(", ", names);
    }

    // ---------------------------------------------------------------- machine

    /// <summary>Total physical memory, as the runtime is allowed to see it.</summary>
    private static string TotalMemory()
    {
        long bytes = GC.GetGCMemoryInfo().TotalAvailableMemoryBytes;
        if (bytes <= 0)
            return "not reported";

        double gigabytes = bytes / (1024.0 * 1024.0 * 1024.0);
        return $"{gigabytes.ToString("F1", CultureInfo.InvariantCulture)} GB " +
               $"({bytes.ToString("N0", CultureInfo.InvariantCulture)} bytes)";
    }

    private static string CpuName() =>
        RegistryString(ProcessorKey, "ProcessorNameString")?.Trim()
        ?? Environment.GetEnvironmentVariable("PROCESSOR_IDENTIFIER")
        ?? "not reported";

    private static string NominalClock()
    {
        int? megahertz = RegistryInt32(ProcessorKey, "~MHz");
        return megahertz is null
            ? "not reported"
            : $"{(megahertz.Value / 1000.0).ToString("F1", CultureInfo.InvariantCulture)} GHz";
    }

    /// <summary>
    /// Physical cores where the platform will say, and logical processors
    /// always. The two differ by hyper-threading, which is worth stating rather
    /// than leaving a reader to guess which of the two a single number is.
    /// </summary>
    private static string CoreCount()
    {
        int logical = Environment.ProcessorCount;
        int? physical = PhysicalCoreCount();

        return physical is null
            ? $"{logical.ToString(CultureInfo.InvariantCulture)} logical processors"
            : $"{physical.Value.ToString(CultureInfo.InvariantCulture)} cores / " +
              $"{logical.ToString(CultureInfo.InvariantCulture)} threads";
    }

    /// <summary>
    /// The edition and build. Windows 11 still reports "Windows 10" in
    /// <c>ProductName</c>, so the build number is what distinguishes them — 22000
    /// and above is Windows 11.
    /// </summary>
    private static string OperatingSystemName()
    {
        string? product = RegistryString(WindowsVersionKey, "ProductName");
        if (product is null)
            return RuntimeInformation.OSDescription;

        if (Environment.OSVersion.Version.Build >= FirstWindows11Build)
            product = product.Replace("Windows 10", "Windows 11", StringComparison.Ordinal);

        // Major.Minor.Build only: the revision is always 0 on Windows, and the
        // fourth component that means anything is the update build revision.
        var osVersion = Environment.OSVersion.Version;
        string version = $"{osVersion.Major.ToString(CultureInfo.InvariantCulture)}." +
                         $"{osVersion.Minor.ToString(CultureInfo.InvariantCulture)}." +
                         $"{osVersion.Build.ToString(CultureInfo.InvariantCulture)}";

        int? updateBuild = RegistryInt32(WindowsVersionKey, "UBR");
        if (updateBuild is not null)
            version += $".{updateBuild.Value.ToString(CultureInfo.InvariantCulture)}";

        string? release = RegistryString(WindowsVersionKey, "DisplayVersion");
        return release is null
            ? $"{product} {version}"
            : $"{product} {release}, build {version}";
    }

    // --------------------------------------------------------------- probing

    private static string? RegistryString(string keyPath, string valueName)
    {
        if (!OperatingSystem.IsWindows())
            return null;

        using var key = Registry.LocalMachine.OpenSubKey(keyPath);
        return key?.GetValue(valueName) as string;
    }

    private static int? RegistryInt32(string keyPath, string valueName)
    {
        if (!OperatingSystem.IsWindows())
            return null;

        using var key = Registry.LocalMachine.OpenSubKey(keyPath);
        return key?.GetValue(valueName) as int?;
    }

    /// <summary>Ask only for core records, so every record returned is one core.</summary>
    private const uint RelationProcessorCore = 0;

    /// <summary>
    /// Counts physical cores. Returns null off Windows, or if the call fails — a
    /// missing row in the report is better than a guessed one.
    /// </summary>
    private static int? PhysicalCoreCount()
    {
        if (!OperatingSystem.IsWindows())
            return null;

        // The first call sizes the buffer: it fails, and writes the length needed.
        uint length = 0;
        GetLogicalProcessorInformationEx(RelationProcessorCore, IntPtr.Zero, ref length);
        if (length == 0)
            return null;

        IntPtr buffer = Marshal.AllocHGlobal((int)length);
        try
        {
            if (!GetLogicalProcessorInformationEx(RelationProcessorCore, buffer, ref length))
                return null;

            // Variable-length records, each starting with a 4-byte relationship
            // and its own 4-byte size, so the only way through them is to walk.
            int cores = 0;
            for (int offset = 0; offset + 8 <= (int)length;)
            {
                int size = Marshal.ReadInt32(buffer, offset + 4);
                if (size <= 0)
                    break;

                cores++;
                offset += size;
            }

            return cores == 0 ? null : cores;
        }
        finally
        {
            Marshal.FreeHGlobal(buffer);
        }
    }

    // DllImport rather than LibraryImport: the source-generated form requires
    // <AllowUnsafeBlocks> across the whole project, which is too broad a change
    // to make for one line of a report. Every parameter here is blittable, so
    // there is no marshalling for the generator to have improved on.
    [DllImport("kernel32.dll", SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    private static extern bool GetLogicalProcessorInformationEx(
        uint relationshipType, IntPtr buffer, ref uint returnedLength);
}
